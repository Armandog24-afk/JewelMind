"""Keeps specs/setting/v1/ honest against the real backend implementation.

Every example, test-vector and the setting registry were generated by
actually running the real Setting System code (see backend/gen_setting_specs.py,
run once and not part of the shipped code or test suite), never hand-invented.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import jsonschema
import pytest

from jewelmind.domain.defaults import default_definition
from jewelmind.domain.schema import SettingType, StoneSpec
from jewelmind.geometry.assemblies.solitaire import build_solitaire_ring
