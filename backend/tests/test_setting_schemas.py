@pytest.mark.parametrize("name", EXAMPLE_FILES)
def test_examples_validate_against_the_setting_definition_schema(name):
    """No `$ref` resolver is needed: the sub-schemas are inlined under
    `$defs`, matching this codebase's specs convention of avoiding
    cross-file `$ref`."""

    schema = _load(SPECS / "setting-definition.schema.json")
    example = _load(SPECS / "examples" / name)
    jsonschema.validate(example["settingDefinition"], schema)


@pytest.mark.parametrize(
    "name,shape,setting_type,count",
    [
        ("round-4-prong.json", "round", "prong", 4),
        ("round-6-prong.json", "round", "prong", 6),
        ("oval-prong.json", "oval", "prong", 6),
        ("round-bezel.json", "round", "bezel", 6),
        ("oval-bezel.json", "oval", "bezel", 6),
    ],
)
def test_examples_reproduce_live(name, shape, setting_type, count):
    example = _load(SPECS / "examples" / name)
    d = _definition(shape=shape, setting_type=setting_type, prong_count=count)
    components, result = generate_setting(setting_definition_from_jdl(d, build_stone_reference(d)))
    comp = next(iter(components.values()))
    recorded = example["generatedComponent"]
    assert comp.name == recorded["componentId"]
    assert round(comp.volume_mm3, 6) == recorded["volumeMm3"]
    assert len(comp.shape.Solids()) == recorded["solidCount"]
    assert result.compatibilityStatus == example["settingGeometryResult"]["compatibilityStatus"]


def test_prong_placement_vectors_reproduce_live():
    vectors = _load(SPECS / "test-vectors" / "prong-placement-vectors.json")
    for vector in vectors["vectors"]:
        d = _definition(
            shape=vector["stoneShape"],
            length=vector["lengthMm"],
            width=vector["widthMm"],
        )
        ref = build_stone_setting_reference(d.stone, build_stone_reference(d))
        positions, strategy = prong_positions(ref, vector["prongCount"], vector["prongRadiusMm"])
        assert strategy == vector["strategy"]
        assert len(positions) == len(vector["positions"])
        for (x, y), recorded in zip(positions, vector["positions"], strict=True):
            assert round(x, 9) == recorded["x"]
            assert round(y, 9) == recorded["y"]


def test_bezel_vectors_reproduce_live():
    vectors = _load(SPECS / "test-vectors" / "bezel-vectors.json")
    for vector in vectors["vectors"]:
        d = _definition(
            shape=vector["stoneShape"],
            setting_type="bezel",
            length=vector["lengthMm"],
            width=vector["widthMm"],
        )
        components, result = generate_setting(
            setting_definition_from_jdl(d, build_stone_reference(d))
        )
        bezel = components["bezel"]
        assert round(bezel.volume_mm3, 6) == vector["volumeMm3"]
        assert len(bezel.shape.Solids()) == vector["solidCount"]
        assert bezel.metadata["stepSafetyRepairApplied"] == vector["stepSafetyRepairApplied"]
        assert result.compatibilityStatus == vector["compatibility"]


def test_backward_compatibility_vector_reproduces_live():
    vectors = _load(SPECS / "test-vectors" / "backward-compatibility-vectors.json")
    for vector in vectors["vectors"]:
        model = build_solitaire_ring(default_definition())
        # Exact: primitive-built prong geometry is bit-identical everywhere.
        assert model.components["prongs"].volume_mm3 == vector["expectedProngVolumeMm3"]
        # Tolerance: an OCCT boolean-fuse volume carries real platform-dependent
        # drift (~6.7e-14 relative between this repo's Windows and CI's Linux
        # build). See `test_setting.py::BOOLEAN_VOLUME_REL_TOL`.
        assert math.isclose(
            model.combined_metal_volume_mm3,
            vector["expectedCombinedMetalVolumeMm3"],
            rel_tol=1e-9,
        ), (
            f"{model.combined_metal_volume_mm3!r} != "
            f"{vector['expectedCombinedMetalVolumeMm3']!r}"
        )
        assert model.setting_result.placementStrategy == vector["expectedPlacementStrategy"]


def test_compatibility_vectors_match_live():
    vectors = _load(SPECS / "test-vectors" / "compatibility-vectors.json")
    assert vectors["vectors"] == compatibility_matrix()
