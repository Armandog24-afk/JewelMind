def _load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def test_all_schema_files_exist_and_are_valid_json_schema():
    for name in SCHEMA_FILES:
        schema = _load_json(SPECS_DIR / name)
        jsonschema.Draft202012Validator.check_schema(schema)


def test_conversation_result_examples_validate_against_schema():
    result_schema = _load_json(SPECS_DIR / "conversation-result.schema.json")
    for name in EXAMPLE_FILES:
        example = _load_json(SPECS_DIR / "examples" / name)
        assert "turns" in example
        for turn_result in example["turns"]:
            jsonschema.validate(turn_result, result_schema)


