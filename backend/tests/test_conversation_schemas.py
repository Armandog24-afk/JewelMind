def test_examples_show_genuinely_distinct_per_turn_state():
    """Regression guard for the mutable-session snapshotting pitfall
    documented in specs/conversation/v1/README.md — every turn in a
    multi-turn example must show its own turn count, not a copy of the
    final session's."""

    for name in EXAMPLE_FILES:
        example = _load_json(SPECS_DIR / "examples" / name)
        turn_counts = [len(t["session"]["turns"]) for t in example["turns"]]
        assert turn_counts == sorted(turn_counts), name
        assert turn_counts == list(range(1, len(turn_counts) + 1)), name


def _strip_generated(result_dict: dict) -> dict:
    """Removes uuid4-based ids and wall-clock timestamps so a live
    re-derivation can be compared against a previously-generated example
    (mirrors _without_generated_ids in test_design_intent_schemas.py)."""

    session = dict(result_dict["session"])
    session.pop("sessionId", None)
    session.pop("createdAt", None)
    session.pop("updatedAt", None)
    session["turns"] = [_strip_turn(t) for t in session.get("turns", [])]
    if session.get("activeProposal") is not None:
        proposal = dict(session["activeProposal"])
        proposal.pop("proposalId", None)
        proposal.pop("turnId", None)
        if proposal.get("designerProposal") is not None:
            designer_proposal = dict(proposal["designerProposal"])
            designer_proposal.pop("proposalId", None)
            proposal["designerProposal"] = designer_proposal
        session["activeProposal"] = proposal
    if session.get("pendingClarification") is not None:
        session["pendingClarification"] = _strip_clarification(session["pendingClarification"])

    return {"session": session, "turn": _strip_turn(dict(result_dict["turn"]))}


def _strip_turn(turn_dict: dict) -> dict:
    turn = dict(turn_dict)
    turn.pop("turnId", None)
    turn.pop("timestamp", None)
    turn.pop("proposalId", None)
    if turn.get("clarification") is not None:
        turn["clarification"] = _strip_clarification(turn["clarification"])
    return turn


def _strip_clarification(clarification_dict: dict) -> dict:
    clarification = dict(clarification_dict)
    clarification.pop("clarificationId", None)
    clarification.pop("originatingTurnId", None)
    clarification.pop("createdAt", None)
    clarification.pop("resolvedAt", None)
    return clarification


def test_create_and_refine_example_is_reproducible_live():
    example = _load_json(SPECS_DIR / "examples" / "create-and-refine.json")

    provider = FakeDesignerProvider(
        responses_by_text={
            "Fammi un solitario in oro rosa con sei griffe.": RawDesignerResponse(
                proposedCanonicalValues=[
                    RawProposedValue(field="material.metal", value="oro rosa"),
                    RawProposedValue(field="setting.prongCount", value="sei"),
                ]
            ),
            "Fallo in platino.": RawDesignerResponse(
                proposedCanonicalValues=[RawProposedValue(field="material.metal", value="platino")]
            ),
        }
    )
    engine = ConversationEngine(designer_service=DesignerService(provider=provider))

    def run(text: str, session=None):
        request = ConversationTurnRequest(
            text=text,
            currentJDL=JewelryDefinition(),
            currentDesignIntent=DEFAULT_INTENT,
            session=session.model_copy(deep=True) if session is not None else None,
        )
        result = engine.process_turn(request)
        return result.model_copy(deep=True)

    r1 = run("Fammi un solitario in oro rosa con sei griffe.")
    r2 = run("ok", session=r1.session)
    r3 = run("Fallo in platino.", session=r2.session)

    live = [
        _strip_generated(json.loads(r1.model_dump_json())),
        _strip_generated(json.loads(r2.model_dump_json())),
        _strip_generated(json.loads(r3.model_dump_json())),
    ]
    recorded = [_strip_generated(t) for t in example["turns"]]
    assert live == recorded
